import 'reflect-metadata';
import assert from 'node:assert/strict';
import test from 'node:test';
import { randomUUID } from 'node:crypto';
import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { NestFactory } from '@nestjs/core';
import { AppModule } from '../app.module';
import { PrismaService } from '../prisma/prisma.service';
import { securityHeadersMiddleware } from '../common/security-headers';
import { ProblemDetailsFilter } from '../common/problem-details.filter';
import { materialRequestFixture } from './material-request-test-fixture';
test('MR-AC-01–07 scoped request/issue/explicit signed receipt HTTP and database contracts', async (t) => {
    const oldStorage = process.env.STORAGE_ROOT, storage = await mkdtemp(path.join(tmpdir(), 'erp-material-request-'));
    process.env.STORAGE_ROOT = storage;
    const db = new PrismaService();
    await db.$connect();
    const app = await NestFactory.create(AppModule, { logger: false });
    app.setGlobalPrefix('api/v1');
    app.use(securityHeadersMiddleware(false));
    app.useGlobalFilters(new ProblemDetailsFilter());
    await app.listen(0, '127.0.0.1');
    try {
        const f = await materialRequestFixture(db), base = await app.getUrl() + '/api/v1', root = '/inventory/material-requests';
        type Actor = typeof f.store;
        const call = async (actor: Actor | undefined, url: string, status = 200, body?: unknown, csrf = true) => {
            const r = await fetch(base + url, { method: body === undefined ? 'GET' : 'POST', headers: { ...(actor ? { Cookie: 'erp_session=' + actor.session.sessionToken } : {}), ...(body !== undefined ? { 'Content-Type': 'application/json' } : {}), ...(actor && csrf ? { 'x-csrf-token': actor.session.csrfToken } : {}) }, ...(body !== undefined ? { body: JSON.stringify(body) } : {}) });
            assert.equal(r.status, status, await r.clone().text());
            assert.equal(r.headers.get('cache-control'), 'private, no-store');
            return await r.json() as any;
        };
        const effects = async () => ({ stock: await db.stockTransaction.count(), reservation: await db.materialReservation.count(), payments: await db.payment.count(), directCosts: await db.directCostPosting.count(), pr: await db.purchaseRequest.count(), po: await db.purchaseOrder.count() });
        let requestId = '', lineId = '';
        await t.test('real authentication, CSRF, explicit rights and input validation precede request capture', async () => {
            const input = f.input();
            await call(undefined, root + '/projects', 401);
            await call(f.foreman, root, 403, input);
            await call(f.administrator, root, 403, input);
            await call(f.store, root, 403, input, false);
            await call(f.store, root, 422, { ...input, companyId: f.foreign.id });
            await call(f.store, root, 422, { ...input, requestDate: '2026-02-30' });
            await call(f.store, root, 422, { ...input, lines: [{ ...input.lines[0], requestedQuantity: '0' }] });
            await call(f.store, root, 422, { ...input, warehouseId: f.foreign.id });
            await call(f.store, root, 422, { ...input, requesterEmployeeId: f.outsider.employee.id });
            await call(f.outsider, root, 403, input);
            const before = await effects(), created = (await call(f.store, root, 201, input)).data;
            assert.deepEqual((await call(f.store, root, 201, input)).data, created);
            requestId = created.id;
            await call(f.store, root, 409, { ...input, remarks: 'different body' });
            assert.deepEqual(await effects(), before, 'capture/replay never posts stock or Finance');
            const emptyWarehouse=await db.warehouse.create({data:{companyId:f.company.id,projectId:f.project.id,warehouseCode:'REQUEST-ONLY',warehouseName:'Request-only warehouse',isSiteWarehouse:true}});
            await call(f.store,root,201,{...f.input(),warehouseId:emptyWarehouse.id});
            await assert.rejects(()=>db.warehouse.update({where:{id:emptyWarehouse.id},data:{projectId:f.unassigned.id}}),'a request-only warehouse cannot silently move Project');
            const detail = (await call(f.store, root + '/' + requestId)).data;
            lineId = detail.lines[0].id;
            assert.equal(detail.lines[0].requestedQuantity, '10.0000');
            assert.equal(detail.lines[0].issuedQuantity, '0.0000');
            assert.equal(detail.lines[0].acknowledgedQuantity, '0.0000');
            await call(f.outsider, root + '/' + requestId, 403);
            assert.equal((await call(f.foreman, root + '/' + requestId)).data.lines[0].issuedQuantity, '0.0000');
        });
        await t.test('same-key concurrent capture is one durable request; stale revisions preserve both facts', async () => {
            const large = f.input('90071992547409.1234'), big = (await call(f.store, root, 201, large)).data;
            assert.equal((await call(f.store, root + '/' + big.id)).data.revisions[0].facts.lines[0].requestedQuantity, '90071992547409.1234');
            const input = f.input();
            const [a, b] = await Promise.all([call(f.store, root, 201, input), call(f.store, root, 201, input)]);
            assert.deepEqual(a.data, b.data);
            assert.equal(await db.materialRequestOperation.count({ where: { requestKey: input.requestKey } }), 1);
            const edit = { requestKey: randomUUID(), expectedVersion: 1, reason: 'Correct quantity with retained original', requestDate: '2026-11-02', remarks: 'Revised note', lines: [{ id: lineId, requestedQuantity: '10.0000', remarks: 'Original quantity retained' }] };
            const [x, y] = await Promise.all([call(f.store, root + '/' + requestId + '/revisions', 201, edit), call(f.store, root + '/' + requestId + '/revisions', 201, edit)]);
            assert.deepEqual(x.data, y.data);
            await call(f.store, root + '/' + requestId + '/revisions', 409, { ...edit, requestKey: randomUUID() });
            const d = (await call(f.store, root + '/' + requestId)).data;
            assert.equal(d.version, 2);
            assert.equal(d.revisions.length, 2);
            assert.equal(d.revisions[0].facts.remarks, 'Oral Foreman request captured by Store');
            await assert.rejects(() => db.materialRequestRevision.update({ where: { id: d.revisions[0].id }, data: { reason: 'replace history' } }));
            await assert.rejects(() => db.materialRequestLine.update({ where: { id: lineId }, data: { requestedQuantity: '11' } }), 'raw mutation cannot bypass revision evidence');
        });
        let firstIssue: Awaited<ReturnType<typeof f.issue>>, linkId = '', docId = '';
        await t.test('only canonical posted lines fulfill requests; link replay has no stock effect', async () => {
            const draft = await f.issue('1', false), d = (await call(f.store, root + '/' + requestId)).data;
            await call(f.store, root + '/' + requestId + '/issue-links', 422, { requestKey: randomUUID(), expectedVersion: d.version, requestLineId: lineId, materialIssueItemId: draft.items[0]!.id, reason: 'Unposted must not fulfill' });
            firstIssue = await f.issue('6');
            const before = await effects();
            const link = { requestKey: randomUUID(), expectedVersion: d.version, requestLineId: lineId, materialIssueItemId: firstIssue.items[0]!.id, reason: 'Link actual first partial issue' };
            const linked = (await call(f.store, root + '/' + requestId + '/issue-links', 201, link)).data;
            assert.deepEqual((await call(f.store, root + '/' + requestId + '/issue-links', 201, link)).data, linked);
            assert.deepEqual(await effects(), before);
            const detail = (await call(f.store, root + '/' + requestId)).data;
            assert.equal(detail.lines[0].issuedQuantity, '6.0000');
            assert.equal(detail.lines[0].acknowledgedQuantity, '0.0000');
            linkId = detail.lines[0].issueLinks[0].id;
            assert.equal((await call(f.foreman, root + '/' + requestId)).data.lines[0].issueLinks[0].issue, null, 'view of request does not grant issue-source details');
            await call(f.store, root + '/' + requestId + '/issue-links', 409, { ...link, requestKey: randomUUID(), expectedVersion: detail.version });
            assert.equal((await call(f.store, root + '/' + requestId)).data.version, detail.version);
        });
        await t.test('upload is not acknowledgment; receipt requires actual actors, explicit signed confirmation and protected source', async () => {
            const doc = await f.upload(requestId);
            docId = doc.id;
            const d = (await call(f.store, root + '/' + requestId)).data;
            assert.equal(d.lines[0].acknowledgedQuantity, '0.0000');
            const receipt = { requestKey: randomUUID(), expectedVersion: d.version, issueLinkId: linkId, recipientEmployeeId: f.foreman.employee.id, issuerEmployeeId: f.store.employee.id, receivedAt: new Date(Date.now() - 60000).toISOString(), documentId: docId, signedEvidenceConfirmed: true, supersedesReceiptId: null, reason: 'Signed paper receipt explicitly recorded' };
            await call(f.store, root + '/' + requestId + '/receipts', 422, { ...receipt, signedEvidenceConfirmed: false });
            await call(f.store, root + '/' + requestId + '/receipts', 422, { ...receipt, recipientEmployeeId: f.store.employee.id });
            await call(f.store, root + '/' + requestId + '/receipts', 422, { ...receipt, issuerEmployeeId: f.outsider.employee.id });
            const privateDownload = await fetch(base + '/documents/projects/' + f.project.id + '/' + docId + '/download', { headers: { Cookie: 'erp_session=' + f.documentOnly.session.sessionToken } });
            assert.equal(privateDownload.status, 404);
            const foreignAlias = await db.documentLink.create({ data: { documentId: docId, entityType: 'PROJECT', entityId: f.unassigned.id, linkedByUserId: f.store.user.id } });
            await call(f.store, root + '/' + requestId + '/receipts', 422, receipt);
            await db.documentLink.delete({ where: { id: foreignAlias.id } });
            const before = await effects(), result = (await call(f.store, root + '/' + requestId + '/receipts', 201, receipt)).data;
            assert.deepEqual((await call(f.store, root + '/' + requestId + '/receipts', 201, receipt)).data, result);
            assert.deepEqual(await effects(), before);
            const detail = (await call(f.store, root + '/' + requestId)).data;
            assert.equal(detail.lines[0].acknowledgedQuantity, '6.0000');
            const original = detail.lines[0].issueLinks[0].receipts[0];
            await assert.rejects(() => db.materialRequestReceipt.update({ where: { id: original.id }, data: { reason: 'tamper' } }));
            await assert.rejects(() => db.document.update({ where: { id: docId }, data: { checksum: 'f'.repeat(64) } }));
            const source = await db.documentLink.findFirstOrThrow({ where: { documentId: docId, entityType: 'MATERIAL_REQUEST' } });
            await assert.rejects(() => db.documentLink.delete({ where: { id: source.id } }));
            await call(f.store, root + '/' + requestId + '/receipts', 409, { ...receipt, requestKey: randomUUID(), expectedVersion: detail.version });
            await call(f.store, root + '/' + requestId + '/receipts', 201, { ...receipt, requestKey: randomUUID(), expectedVersion: detail.version, supersedesReceiptId: original.id, reason: 'Append corrected observed receipt time', receivedAt: new Date(Date.now() - 30000).toISOString() });
            const corrected = (await call(f.store, root + '/' + requestId)).data.lines[0].issueLinks[0].receipts;
            assert.equal(corrected.length, 2);
            assert.equal(corrected[0].superseded, true);
            assert.equal(corrected[0].reason, receipt.reason);
            const denied = await fetch(base + '/documents/projects/' + f.project.id + '/' + docId + '/download', { headers: { Cookie: 'erp_session=' + f.foreman.session.sessionToken } });
            assert.equal(denied.status, 403);
            const bytes = await f.targets.download(f.store.auth, f.project.id, 'MATERIAL_REQUEST', requestId, docId);
            assert.deepEqual(bytes.bytes, f.bytes);
            const stored=await db.document.findUniqueOrThrow({where:{id:docId}});
            const ownFile=path.resolve(storage,stored.storageKey);assert.ok(ownFile.startsWith(storage+path.sep));
            await writeFile(ownFile,Buffer.from('tampered signed evidence'));
            await assert.rejects(()=>f.targets.download(f.store.auth,f.project.id,'MATERIAL_REQUEST',requestId,docId));
            await writeFile(ownFile,f.bytes);

        });
        await t.test('partial 6 then 4 reconciles; canonical reversal changes totals while retaining signed evidence', async () => {
            const second = await f.issue('4'), d = (await call(f.store, root + '/' + requestId)).data;
            await call(f.store, root + '/' + requestId + '/issue-links', 201, { requestKey: randomUUID(), expectedVersion: d.version, requestLineId: lineId, materialIssueItemId: second.items[0]!.id, reason: 'Link remaining canonical issue' });
            assert.equal((await call(f.store, root + '/' + requestId)).data.lines[0].issuedQuantity, '10.0000');
            await f.issues.reverse({ auth: f.store.auth }, firstIssue!.id, randomUUID(), 'Reverse first actual issue');
            const after = (await call(f.store, root + '/' + requestId)).data;
            assert.equal(after.lines[0].issuedQuantity, '4.0000');
            assert.equal(after.lines[0].acknowledgedQuantity, '0.0000');
            assert.equal(after.lines[0].issueLinks[0].receipts.length, 2);
            assert.equal(await db.document.count({ where: { id: docId } }), 1);
        });
        await t.test('persisted permission revocation defeats stale sessions and forged access-all', async () => {
            const original = f.store.auth.permissions;
            const p = await db.permission.findUniqueOrThrow({ where: { permissionCode: 'inventory.material_request.view' } });
            await db.rolePermission.delete({ where: { roleId_permissionId: { roleId: f.store.role.id, permissionId: p.id } } });
            await assert.rejects(() => f.service.get({ ...f.store.auth, permissions: original.concat('projects.access_all') }, requestId));
            await call(f.store, root + '/' + requestId, 403);
            await assert.rejects(() => f.service.get({ ...f.outsider.auth, permissions: f.outsider.auth.permissions.concat('projects.access_all') }, requestId));
        });
    }
    finally {
        await app.close();
        await db.$disconnect();
        if (oldStorage === undefined)
            delete process.env.STORAGE_ROOT;
        else
            process.env.STORAGE_ROOT = oldStorage;
        await rm(storage, { recursive: true, force: true });
    }
});
